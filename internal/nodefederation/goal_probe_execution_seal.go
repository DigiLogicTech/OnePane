package nodefederation

import (
 "bytes"
 "crypto/ed25519"
 "crypto/x509"
 "encoding/json"
 "errors"
 "time"

 "github.com/DigiLogicTech/OnePane/internal/projectworkspace"
)

// SealedNodeProbeAuthority is a single, historically signed server-side
// human permit snapshot. It is only key-authenticated if the verifier
// independently possesses the original pinned OnePane local Node leaf.
// It is NOT a statement of physical host or observed remote device truth.
type SealedNodeProbeAuthority struct {
 SigningPayload []byte `json:"signing_payload"`
 Signature []byte `json:"signature"`
}

const serverProbeSealDomain="OnePane/server-node-probe-authority/ed25519/v1"

type serverProbeSealEnvelope struct {
 Domain string `json:"domain"`
 ServerNodeID string `json:"server_node_id"`
 ServerCertificateSHA256 string `json:"server_certificate_sha256"`
 SignedAt int64 `json:"signed_at"`
 Permit projectworkspace.GoalNodeProbeExecutionPermit `json:"permit"`
}

func serverProbeSealPayload(nodeID,fp string,p projectworkspace.GoalNodeProbeExecutionPermit,
 signedAt int64)([]byte,error){
 if nodeID==""||len(fp)!=71||p.ID==""||p.Status!="approved"||
  p.EffectiveExecutionState!="active"||p.Revision!=1||
  p.OperatorPublicKeySHA256==""||p.PlanGeneration<1||
  p.PlanSHA256==""||p.PeerNodeID==""||p.ApprovedBy==""||
  signedAt<p.ApprovedAt||signedAt>=p.ExpiresAt{
  return nil,errors.New("not a live human-authorised original one-shot grant")
 }
 result,err:=json.Marshal(serverProbeSealEnvelope{
  Domain:serverProbeSealDomain,ServerNodeID:nodeID,
  ServerCertificateSHA256:fp,SignedAt:signedAt,Permit:p,
 })
 if err!=nil{return nil,err}
 if len(result)>4096{return nil,errors.New("server seal exceeds bounded scope")}
 return result,nil
}

// SealHumanNodeProbeExecution may only be called after an authenticated
// human API has independently fetched CURRENT effective grant state.
// Local Node identity is existing, not generated by this function.
func SealHumanNodeProbeExecution(ident Identity,
 p projectworkspace.GoalNodeProbeExecutionPermit, now time.Time)(
 SealedNodeProbeAuthority,error){
 if len(ident.Certificate.Certificate)!=1{
  return SealedNodeProbeAuthority{},errors.New("existing OnePane server identity required")
 }
 cert,err:=x509.ParseCertificate(ident.Certificate.Certificate[0])
 if err!=nil{return SealedNodeProbeAuthority{},err}
 if err=ValidateLocalInstrumentCustodyIdentity(cert.Subject.CommonName,ident,now);
  err!=nil{return SealedNodeProbeAuthority{},err}
 private,ok:=ident.Certificate.PrivateKey.(ed25519.PrivateKey)
 if !ok||len(private)!=ed25519.PrivateKeySize{
  return SealedNodeProbeAuthority{},errors.New("server identity cannot sign")
 }
 payload,err:=serverProbeSealPayload(cert.Subject.CommonName,ident.Fingerprint,p,now.UnixMilli())
 if err!=nil{return SealedNodeProbeAuthority{},err}
 return SealedNodeProbeAuthority{
  SigningPayload:payload,Signature:ed25519.Sign(private,payload),
 },nil
}

// VerifySealedNodeProbeExecution requires externally enrolled ORIGINAL
// OnePane server certificate DER and exact fingerprint: fields in the
// signed envelope are not trusted independently. A historical seal is
// not an online revocation check or permission for a fresh network action.
func VerifySealedNodeProbeExecution(s SealedNodeProbeAuthority,
 originalServerCertDER []byte,knownServerNodeID,knownFingerprint string)(
 projectworkspace.GoalNodeProbeExecutionPermit,error){
 var empty projectworkspace.GoalNodeProbeExecutionPermit
 if len(s.SigningPayload)==0||len(s.SigningPayload)>4096||
  len(s.Signature)!=ed25519.SignatureSize{return empty,errors.New("invalid server signature envelope")}
 cert,err:=x509.ParseCertificate(originalServerCertDER)
 if err!=nil{return empty,err}
 var env serverProbeSealEnvelope
 if err=json.Unmarshal(s.SigningPayload,&env);err!=nil{return empty,err}
 if env.Domain!=serverProbeSealDomain||
  env.ServerNodeID!=knownServerNodeID||
  env.ServerCertificateSHA256!=knownFingerprint{
  return empty,errors.New("independent OnePane server origin mismatch")
 }
 if err=validateCustodyCert(cert,knownServerNodeID,knownFingerprint,
  env.SignedAt);err!=nil{return empty,err}
 expected,err:=serverProbeSealPayload(knownServerNodeID,knownFingerprint,env.Permit,env.SignedAt)
 if err!=nil{return empty,err}
 if !bytes.Equal(expected,s.SigningPayload)||
  !ed25519.Verify(cert.PublicKey.(ed25519.PublicKey),s.SigningPayload,s.Signature){
  return empty,errors.New("OnePane original server execution signature invalid")
 }
 return env.Permit,nil
}

// VerifySealedNodeProbeExecutionAtObservation enforces historical temporal
// causality: an operator must not attach a NEW server approval, however
// correctly signed, to a signed instrument receipt from BEFORE that approval.
// The original signature is still checked by VerifySealedNodeProbeExecution.
// This does not prove trusted clocks, physical execution or live revocation.
func VerifySealedNodeProbeExecutionAtObservation(
 s SealedNodeProbeAuthority,originalServerCertDER []byte,
 knownServerNodeID,knownFingerprint string,observedAt int64)(
 projectworkspace.GoalNodeProbeExecutionPermit,error){
 permit,err:=VerifySealedNodeProbeExecution(s,originalServerCertDER,
  knownServerNodeID,knownFingerprint)
 if err!=nil{return permit,err}
 var envelope struct{SignedAt int64 `json:"signed_at"`}
 if err=json.Unmarshal(s.SigningPayload,&envelope);err!=nil{return permit,err}
 if observedAt<permit.ApprovedAt||observedAt<envelope.SignedAt||
  observedAt>=permit.ExpiresAt{
  return projectworkspace.GoalNodeProbeExecutionPermit{},
   errors.New("OnePane server execution seal is newer than observation or outside original approved window")
 }
 return permit,nil
}
